enum EntryKind {
  expense('Expense'),
  income('Income');

  const EntryKind(this.label);
  final String label;
}

String dateKey(DateTime value) =>
    '${value.year.toString().padLeft(4, '0')}-${value.month.toString().padLeft(2, '0')}-${value.day.toString().padLeft(2, '0')}';

int? parseCents(String input) {
  final value = input.trim();
  if (!RegExp(r'^\d{1,9}([.,]\d{1,2})?$').hasMatch(value)) return null;
  final parts = value.replaceAll(',', '.').split('.');
  final cents =
      int.parse(parts[0]) * 100 +
      (parts.length == 2 ? int.parse(parts[1].padRight(2, '0')) : 0);
  return cents > 0 ? cents : null;
}

String money(int cents) =>
    '${cents < 0 ? '-' : ''}\$${(cents.abs() / 100).toStringAsFixed(2)}';

class LedgerEntry {
  const LedgerEntry({
    required this.id,
    required this.business,
    required this.category,
    required this.cents,
    required this.date,
    required this.kind,
    this.ruleId,
  });
  final int id;
  final String business;
  final String category;
  final int cents;
  final DateTime date;
  final EntryKind kind;

  /// Set when the entry was generated by a monthly rule.
  final int? ruleId;

  factory LedgerEntry.fromRow(Map<String, Object?> row) => LedgerEntry(
    id: row['id'] as int,
    business: row['business'] as String,
    category: row['category'] as String,
    cents: row['cents'] as int,
    date: DateTime.parse(row['date'] as String),
    kind: EntryKind.values.byName(row['kind'] as String),
    ruleId: row['rule_id'] as int?,
  );
}

class MonthlyRule {
  const MonthlyRule({
    required this.id,
    required this.business,
    required this.category,
    required this.cents,
    required this.start,
    required this.kind,
  });
  final int id;
  final String business;
  final String category;
  final int cents;
  final DateTime start;
  final EntryKind kind;

  factory MonthlyRule.fromRow(Map<String, Object?> row) => MonthlyRule(
    id: row['id'] as int,
    business: row['business'] as String,
    category: row['category'] as String,
    cents: row['cents'] as int,
    start: DateTime.parse(row['start'] as String),
    kind: EntryKind.values.byName(row['kind'] as String),
  );
}

// Clamp to the last day of short months without drifting the original due day.
Iterable<DateTime> monthlyDates(DateTime start, DateTime through) sync* {
  var month = DateTime(start.year, start.month);
  final end = DateTime(through.year, through.month, through.day);
  while (!month.isAfter(end)) {
    final lastDay = DateTime(month.year, month.month + 1, 0).day;
    final due = DateTime(
      month.year,
      month.month,
      start.day > lastDay ? lastDay : start.day,
    );
    if (!due.isAfter(end)) yield due;
    month = DateTime(month.year, month.month + 1);
  }
}
